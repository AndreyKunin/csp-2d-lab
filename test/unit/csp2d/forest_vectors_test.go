// Forest vectors: layouts decoded by the server, for the frontend tests
// (static/test/forests.test.ts). The UI rebuilds every sheet from its tree
// string (getTree, joinRects in static/src/utils/rect.ts) and places the parts
// (computeLayout in static/src/utils/layout.ts); that code duplicates the
// server's reduce() and must not diverge from it. The vectors carry what the
// server computed for each sheet, so the frontend tests check the UI against
// the server, not against a second copy of the same rules.
//
// The file is generated by this test: CSP2D_UPDATE_VECTORS=1 writes it;
// otherwise the test regenerates the vectors and fails if they differ from
// the file, so a change of the server's decoding cannot go unnoticed by the
// frontend tests.

// forestCase is one instance as the UI enters it, with layouts the server
// decoded for it.
type forestCase struct {
	Name     string      `json:"name"`
	Unit     string      `json:"unit"`     // "mm": decimal sizes; "in": fractions (exact in both)
	Parts    [][3]string `json:"parts"`    // rows as the UI enters them: width, length, count; label = row number
	Sheet    *[2]string  `json:"sheet"`    // width, length as entered (not normalised); nil = unlimited
	SawWidth string      `json:"sawWidth"` // as entered
	Layouts  []forestCut `json:"layouts"`  // decoded random genotypes
}

// forestCut is one decoded genotype: its sheets in the order of the server's
// response.
type forestCut struct {
	Postfix string        `json:"postfix"` // the whole genotype by label (for diagnostics)
	Sheets  []forestSheet `json:"sheets"`
}

// forestSheet is one sheet: the tree the server sends (SheetLayout.Tree) and
// the size the server computed for it (MeteredNode.measurements).
type forestSheet struct {
	Tree  string  `json:"tree"`
	Long  float64 `json:"long"`
	Short float64 `json:"short"`
}

const forestVectorsPath = "test/testdata/forests/forests.json"

func repoPath(t *testing.T, rel string) string {
	t.Helper()
	_, file, _, _ := runtime.Caller(0)
	return filepath.Join(filepath.Dir(file), "..", "..", "..", filepath.FromSlash(rel))
}

// formatSize writes v as the UI's user would: a decimal, or (unit "in") a
// whole number and a dyadic fraction ("12 3/8", "5/16").
func formatSize(v float64, unit string) string {
	if unit != "in" || v == math.Trunc(v) {
		return strconv.FormatFloat(v, 'f', -1, 64)
	}
	whole := math.Floor(v)
	num, den := v-whole, 1.0
	for num != math.Trunc(num) {
		num, den = num*2, den*2
	}
	frac := fmt.Sprintf("%d/%d", int(num), int(den))
	if whole == 0 {
		return frac
	}
	return fmt.Sprintf("%d %s", int(whole), frac)
}

// generateForestCases builds the vectors deterministically.
func generateForestCases(t *testing.T) []forestCase {
	t.Helper()
	rnd := rand.New(rand.NewSource(20261123))
	type variant struct {
		unit    string
		sheet   bool
		swapped bool    // the sheet entered as width < length
		kerf    float64 // saw width
		step    float64 // size granularity
	}
	variants := []variant{
		{"mm", false, false, 0, 1},
		{"mm", false, false, 3.2, 0.5},
		{"mm", true, false, 0, 1},
		{"mm", true, false, 2.4, 0.5},
		{"mm", true, true, 0, 1},
		{"mm", true, true, 3.2, 1},
		{"in", false, false, 0.125, 0.0625},
		{"in", true, false, 0.09375, 0.125},
		{"in", true, true, 0.125, 0.0625},
		{"in", true, false, 0, 0.25},
	}
	var cases []forestCase
	for vi, v := range variants {
		for k := 0; k < 12; k++ {
			c := forestCase{Name: fmt.Sprintf("v%d-%s-%d", vi, v.unit, k), Unit: v.unit, SawWidth: formatSize(v.kerf, v.unit)}
			sheetLong, sheetShort := 0.0, 0.0
			if v.sheet {
				sheetShort = float64(60+rnd.Intn(80)) * v.step * 8
				sheetLong = sheetShort + float64(rnd.Intn(80))*v.step*8
				w, l := sheetLong, sheetShort
				if v.swapped {
					w, l = l, w
				}
				c.Sheet = &[2]string{formatSize(w, v.unit), formatSize(l, v.unit)}
			}
			// Distinct part sizes (the UI rejects duplicate dimensions); every part
			// fits the sheet.
			maxSide := 400.0 * v.step
			if v.sheet {
				maxSide = sheetShort
			}
			rows := 1 + rnd.Intn(14)
			if k%4 == 0 {
				rows = 1 + rnd.Intn(3) // small cases: easier to read when one fails
			}
			seen := map[[2]float64]bool{}
			var inputs []csp2d.InputDefinition
			for len(c.Parts) < rows {
				w := float64(1+rnd.Intn(int(maxSide/v.step))) * v.step
				l := float64(1+rnd.Intn(int(maxSide/v.step))) * v.step
				if seen[[2]float64{math.Max(w, l), math.Min(w, l)}] {
					continue
				}
				seen[[2]float64{math.Max(w, l), math.Min(w, l)}] = true
				count := 1 + rnd.Intn(3)
				label := strconv.Itoa(len(c.Parts) + 1)
				c.Parts = append(c.Parts, [3]string{formatSize(w, v.unit), formatSize(l, v.unit), strconv.Itoa(count)})
				for j := 0; j < count; j++ {
					intLabel, _ := strconv.Atoi(label)
					inputs = append(inputs, csp2d.InputDefinition{Id: len(inputs), Label: label, IntLabel: intLabel,
						LongSide: math.Max(w, l), ShortSide: math.Min(w, l)})
				}
			}
			maxL, maxS := -1.0, -1.0
			if v.sheet {
				maxL, maxS = sheetLong, sheetShort
			}
			p := csp2d.NewProblemForTest(inputs, csp2d.NewConstraints(maxL, maxS, v.kerf))
			p.InitForTest(8, 2)
			for g := 0; g < 4; g++ {
				ind, err := p.NewRandomIndividual(rnd)
				if err != nil || ind == nil {
					t.Fatalf("%s: random individual: %v", c.Name, err)
				}
				individual := csp2d.AsIndividualForTest(ind)
				forest, err := p.GetForestForTest(individual)
				if err != nil {
					t.Fatalf("%s: decode: %v", c.Name, err)
				}
				cut := forestCut{Postfix: p.ToStringForTest(individual.PostfixForTest())}
				for _, sheet := range forest {
					cut.Sheets = append(cut.Sheets, forestSheet{Tree: p.ToStringForTest(sheet.Postfix), Long: sheet.Long, Short: sheet.Short})
				}
				c.Layouts = append(c.Layouts, cut)
			}
			cases = append(cases, c)
		}
	}
	return cases
}

// UT-FV-01: the forest vectors file is what the server decodes now.
func TestForestVectorsAreCurrent(t *testing.T) {
	cases := generateForestCases(t)
	data, err := json.MarshalIndent(cases, "", " ")
	if err != nil {
		t.Fatal(err)
	}
	data = append(data, '\n')
	path := repoPath(t, forestVectorsPath)
	if os.Getenv("CSP2D_UPDATE_VECTORS") == "1" {
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, data, 0o644); err != nil {
			t.Fatal(err)
		}
		t.Logf("wrote %d cases to %s", len(cases), forestVectorsPath)
		return
	}
	current, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("%v (generate it with CSP2D_UPDATE_VECTORS=1)", err)
	}
	if !bytes.Equal(bytes.ReplaceAll(current, []byte("\r\n"), []byte("\n")), data) {
		t.Fatalf("%s is not what the server decodes now: regenerate it with CSP2D_UPDATE_VECTORS=1 "+
			"and run the frontend tests (cd static && npm test)", forestVectorsPath)
	}
	sheets, multi := 0, 0
	for _, c := range cases {
		for _, l := range c.Layouts {
			sheets += len(l.Sheets)
			if len(l.Sheets) > 1 {
				multi++
			}
		}
	}
	if multi == 0 {
		t.Error("no layout spans several sheets: the vectors do not exercise the sheet split")
	}
	t.Logf("%d cases, %d sheets, %d multi-sheet layouts", len(cases), sheets, multi)
}
